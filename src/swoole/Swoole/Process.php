    /**
     * Set the read and write timeout on the pipe of the process.
     *
     * @param float $seconds The timeout in seconds. When 0 is passed, the timeout is disabled, which means read and
     *                       write operations on the pipe block until they are done.
     * @return bool Returns true on success or false on failure. It also returns false, with an E_WARNING level error
     *              thrown out, when the process doesn't have a pipe.
     * @see \Swoole\Process::setBlocking()
     */
    public function setTimeout(float $seconds): bool
    {
    }

    public function setBlocking(bool $blocking): void
    {
    }

    /**
     * Create (or get access to) a System V message queue, and use it to exchange data between the process and the
     * process where the Process object is created.
     *
     * Once this method is called successfully, properties $msgQueueId and $msgQueueKey are set accordingly.
     *
     * Every message in a System V message queue carries a positive integer called the message type (the "mtype" field
     * of the message passed to system call msgsnd(), and the "msgtyp" argument of system call msgrcv()), which allows a
     * reader to fetch messages selectively. Swoole uses ($this->id + 1) as the message type of the process; 1 is added
     * because a message type must be greater than 0, while $this->id can be 0.
     *
     * There are two modes of the message queue:
     *   - SWOOLE_MSGQUEUE_ORIENT (1): Method \Swoole\Process::pop() passes ($this->id + 1) as the "msgtyp" argument of
     *     system call msgrcv(), and thus only fetches messages of that message type from the queue.
     *   - SWOOLE_MSGQUEUE_BALANCE (2, the default): Method \Swoole\Process::pop() passes 0 as the "msgtyp" argument of
     *     system call msgrcv(), and thus fetches the first message in the queue, no matter what message type it is of.
     *
     * Either mode can be combined with constant \Swoole\Process::IPC_NOWAIT (256), e.g.,
     * SWOOLE_MSGQUEUE_BALANCE | \Swoole\Process::IPC_NOWAIT, to make the queue non-blocking. In that case, methods
     * \Swoole\Process::push() and \Swoole\Process::pop() return false immediately instead of blocking, when the queue
     * is full or empty.
     *
     * Please note that no matter which mode is used, messages pushed through method \Swoole\Process::push() always
     * carry message type ($this->id + 1).
     *
     * @param int $key Key of the message queue, which is passed to system call msgget() together with flag IPC_CREAT
     *                 and permissions 0666. When 0 or a negative integer is passed, the key generated by calling
     *                 system call ftok() on the PHP file where this method is called is used instead; the "proj_id"
     *                 argument of ftok() (see ftok(3) below) is hardcoded to 1 in Swoole.
     * @param int $mode Mode of the message queue, as described above.
     * @param int $capacity Maximum number of bytes allowed in the message queue (msg_qbytes). The system default is
     *                      used when a non-positive integer is passed.
     * @return bool Returns true on success or false on failure.
     * @see \Swoole\Process::$msgQueueId
     * @see \Swoole\Process::$msgQueueKey
     * @see \Swoole\Process::push()
     * @see \Swoole\Process::pop()
     * @see \Swoole\Process::statQueue()
     * @see \Swoole\Process::freeQueue()
     * @see https://www.man7.org/linux/man-pages/man3/ftok.3.html
     * @see https://www.man7.org/linux/man-pages/man2/msgget.2.html
     * @see https://www.man7.org/linux/man-pages/man2/msgsnd.2.html
     * @see https://www.man7.org/linux/man-pages/man2/msgrcv.2.html
     */
    public function useQueue(int $key = 0, int $mode = 2, int $capacity = -1): bool
    {
    }

    /**
     * Get statistics of the message queue used by the process.
     *
     * @return array{queue_num: int, queue_bytes: int}|false Returns an array containing the number of messages
     *                                                       currently in the queue ("queue_num") and the number of
     *                                                       bytes currently in the queue ("queue_bytes"); returns
     *                                                       false on failure.
     * @see \Swoole\Process::useQueue()
     */
    public function statQueue(): array|false
    {
    }

    /**
     * Destroy the message queue used by the process, and release all the resources (messages included) associated
