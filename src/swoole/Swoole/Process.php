    /**
     * Replace the image of the current process with the given executable, through system call execv().
     *
     * On success, this method never returns: the current process keeps its process ID, but the PHP interpreter (its
     * memory, opened resources, registered callbacks, etc.) is replaced by the given program. Therefore, this method
     * returns a value only when it fails.
     *
     * @param string $exec_file Path of the executable file. It's passed to system call execv() as is, which means
     *                          environment variable PATH is not searched and thus an absolute path should be used.
     * @param array $args Arguments to be passed to the executable file. Each element is converted to string
     *                    implicitly. $exec_file itself is passed as the first argument (argv[0]) implicitly, and thus
     *                    should not be included in this array.
     * @return bool Returns false, with an E_WARNING level error thrown out, when the executable file can't be
     *              executed. Nothing is returned on success.
     */
    public function exec(string $exec_file, array $args): bool
    {
    }

